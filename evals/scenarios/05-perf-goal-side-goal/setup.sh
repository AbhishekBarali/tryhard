cat > wordfreq.py <<'EOF'
"""Print the 20 most common words in a text file, most common first.

Ties are broken alphabetically. Words are lowercased runs of letters.
"""
import sys


def is_letter(ch):
    return ("a" <= ch <= "z") or ("A" <= ch <= "Z")


def split_words(text):
    words = []
    current = ""
    for ch in text:
        if is_letter(ch):
            current = current + ch.lower()
        else:
            if current != "":
                words.append(current)
            current = ""
    if current != "":
        words.append(current)
    return words


def count_words(words):
    unique = []
    for w in words:
        if w not in unique:
            unique.append(w)
    counts = []
    for u in unique:
        counts.append((u, words.count(u)))
    return counts


def top(counts, n):
    ordered = sorted(counts, key=lambda pair: pair[0])
    ordered = sorted(ordered, key=lambda pair: pair[1], reverse=True)
    result = []
    for i in range(min(n, len(ordered))):
        result.append(ordered[i])
    return result


def main(path):
    with open(path) as f:
        text = f.read()
    words = split_words(text)
    counts = count_words(words)
    for word, count in top(counts, 20):
        print(f"{count} {word}")


if __name__ == "__main__":
    main(sys.argv[1])
EOF

cat > bench/make_input.py <<'EOF'
import random

random.seed(7)
syllables = ["ka", "lo", "mi", "ne", "su", "ta", "ri", "po", "ve", "do", "an", "el"]
vocab = ["".join(random.choice(syllables) for _ in range(random.randint(1, 4))) for _ in range(3000)]
weights = [1 / (i + 1) for i in range(len(vocab))]
words = random.choices(vocab, weights=weights, k=60000)
with open("bench/input.txt", "w") as f:
    for i in range(0, len(words), 12):
        f.write(" ".join(words[i:i + 12]).capitalize() + ".\n")
EOF

cat > bench/run.py <<'EOF'
"""Benchmark for wordfreq.py. Do not edit this file.

Prints the median wall time of 3 runs and checks the output did not change.
"""
import hashlib
import statistics
import subprocess
import sys
import time

EXPECTED = open("bench/expected.sha256").read().strip()
times = []
for _ in range(3):
    start = time.perf_counter()
    out = subprocess.run([sys.executable, "wordfreq.py", "bench/input.txt"], capture_output=True, check=True).stdout
    times.append(time.perf_counter() - start)
    if hashlib.sha256(out).hexdigest() != EXPECTED:
        sys.exit("FAIL: output changed")
print(f"median {statistics.median(times):.3f} s  (runs: {', '.join(f'{t:.3f}' for t in times)})")
EOF

